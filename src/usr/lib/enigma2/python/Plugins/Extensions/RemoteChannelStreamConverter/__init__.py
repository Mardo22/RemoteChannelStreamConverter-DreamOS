def currentLanguage():
	lang = "auto"
	try:
		lang = config.plugins.RemoteStreamConverter.language.value
	except Exception:
		pass
	if lang == "auto":
		try:
			lang = config.osd.language.value[:2]
		except Exception:
			lang = "en"
	return lang


def _(txt):
	table = TRANSLATIONS.get(currentLanguage())
	if table:
		return table.get(txt, txt)
	return txt
